#!/usr/bin/env python3
"""Rebuild the screenshot gallery in README.md from docs/screenshots/<simulator>/<robot>.png.

  python3 scripts/make_gallery.py          # rewrite the block between the gallery markers
  python3 scripts/make_gallery.py --check  # exit 1 if README is out of date (CI)

Robots missing a picture get "—", so the table also shows what is still to be captured.
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import REPO, SCREENSHOT_DIR, SIMULATORS, load_registry  # noqa: E402

START, END = "<!-- gallery:start -->", "<!-- gallery:end -->"


def build() -> str:
    reg = load_registry()["robots"]
    sims = list(SIMULATORS)
    lines = [START,
             "<!-- generated by scripts/make_gallery.py - do not edit by hand -->",
             "| Robot | " + " | ".join(SIMULATORS[s] for s in sims) + " |",
             "|---|" + ":-:|" * len(sims)]
    n = 0
    for robot in reg:
        cells = []
        for s in sims:
            img = SCREENSHOT_DIR / s / f"{robot}.png"
            if img.exists():
                rel = img.relative_to(REPO).as_posix()
                cells.append(f'<a href="{rel}"><img src="{rel}" width="180" alt="{robot} in {SIMULATORS[s]}"/></a>')
                n += 1
            else:
                cells.append("—")
        lines.append(f"| `{robot}` | " + " | ".join(cells) + " |")
    total = len(reg) * len(sims)
    lines += ["", f"<sub>{n}/{total} screenshots captured. "
                  "Regenerate: see [Screenshots](#screenshots).</sub>", END]
    return "\n".join(lines)


def main() -> int:
    readme = REPO / "README.md"
    text = readme.read_text()
    if START not in text or END not in text:
        sys.exit(f"README.md lacks {START} ... {END} markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = head + build() + tail
    if "--check" in sys.argv:
        if new != text:
            print("README gallery is out of date: run python3 scripts/make_gallery.py")
            return 1
        return 0
    readme.write_text(new)
    print("README gallery updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
